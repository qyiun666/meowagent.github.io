  /* === 检测语言 === */
  function detectLang() {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
    const browser = navigator.language || navigator.languages?.[0] || '';
    return browser.startsWith('zh') ? 'zh' : 'en';
  }

  /* === 切换语言 === */
  window.currentLang = detectLang();

  window.setLang = function (lang) {
    window.currentLang = lang;
    localStorage.setItem(LANG_KEY, lang);
    applyLang(lang);
    updateToggleBtn(lang);
  };

  function applyLang(lang) {
    const data = dict[lang];
    if (!data) return;
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (data[key] !== undefined) {
        el.innerHTML = data[key];
      }
    });
    // 页面标题和 meta 描述
    const pageTitleKey = document.documentElement.getAttribute('data-i18n-page-title');
    if (pageTitleKey && data[pageTitleKey]) {
      document.title = data[pageTitleKey];
    }
    const pageDescEl = document.querySelector('meta[name="description"]');
    if (pageDescEl) {
      const pageDescKey = pageDescEl.getAttribute('data-i18n-key');
      if (pageDescKey && data[pageDescKey]) {
        pageDescEl.setAttribute('content', data[pageDescKey]);
      }
    }
  }

  function updateToggleBtn(lang) {
    const btn = document.getElementById('langToggle');
    if (!btn) return;
    const label = btn.querySelector('.lang-label');
    if (label) {
      label.textContent = lang === 'zh' ? 'EN' : '中文';
    }
  }

  /* === 初始化 === */
  document.addEventListener('DOMContentLoaded', () => {
    applyLang(window.currentLang);
    updateToggleBtn(window.currentLang);

    const btn = document.getElementById('langToggle');
    if (btn) {
      btn.addEventListener('click', () => {
        const next = window.currentLang === 'zh' ? 'en' : 'zh';
        window.setLang(next);
      });
    }
  });

